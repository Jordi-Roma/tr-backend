CREATE TABLE IF NOT EXISTS empresa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    codigo VARCHAR(40) NOT NULL UNIQUE,
    estado VARCHAR(20) NOT NULL DEFAULT 'ACTIVA',
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_empresa_codigo CHECK (codigo ~ '^[a-z0-9][a-z0-9-]{1,39}$'),
    CONSTRAINT ck_empresa_estado CHECK (estado IN ('ACTIVA', 'SUSPENDIDA', 'CANCELADA'))
);

CREATE TABLE IF NOT EXISTS plan (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(50) NOT NULL UNIQUE,
    nombre VARCHAR(120) NOT NULL,
    limites JSONB NOT NULL DEFAULT '{}'::jsonb,
    funciones JSONB NOT NULL DEFAULT '{}'::jsonb,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_plan_limites_objeto CHECK (jsonb_typeof(limites) = 'object'),
    CONSTRAINT ck_plan_funciones_objeto CHECK (jsonb_typeof(funciones) = 'object')
);

CREATE TABLE IF NOT EXISTS suscripcion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT NOT NULL REFERENCES empresa(id) ON DELETE RESTRICT,
    plan_id BIGINT NOT NULL REFERENCES plan(id) ON DELETE RESTRICT,
    estado VARCHAR(20) NOT NULL DEFAULT 'ACTIVA',
    fecha_inicio DATE NOT NULL DEFAULT CURRENT_DATE,
    fecha_vencimiento DATE,
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_suscripcion_estado CHECK (estado IN ('ACTIVA', 'SUSPENDIDA', 'VENCIDA', 'CANCELADA')),
    CONSTRAINT ck_suscripcion_fechas CHECK (fecha_vencimiento IS NULL OR fecha_vencimiento >= fecha_inicio)
);

