-- permiso se mantienen globales en esta primera version.
DO $$
DECLARE
    tabla TEXT;
    relacion RECORD;
    empresa_stylear_id BIGINT;
    total_sin_empresa BIGINT;
    tablas_empresa TEXT[] := ARRAY[
        'usuario', 'sesion', 'sucursal', 'cliente', 'empleado',
        'proveedor', 'categoria', 'talla', 'color', 'temporada',
        'coleccion', 'marca', 'producto', 'producto_variante',
        'precio_producto', 'promocion', 'inventario_sucursal',
        'movimiento_inventario', 'transferencia_stock', 'carrito',
        'reserva', 'venta', 'orden_pago', 'delivery', 'devolucion',
        'reporte_programado', 'bitacora', 'proveedor_usuario',
        'producto_embedding', 'cliente_favorito',
        'cliente_preferencia_ia', 'registro_vestidor'
    ];
BEGIN
    SELECT id INTO STRICT empresa_stylear_id FROM empresa WHERE codigo = 'stylear';

    FOREACH tabla IN ARRAY tablas_empresa LOOP
        IF to_regclass(format('public.%I', tabla)) IS NULL THEN
            RAISE EXCEPTION 'Falta tabla obligatoria para multitenant: %', tabla;
        END IF;

        EXECUTE format('ALTER TABLE public.%I ADD COLUMN IF NOT EXISTS empresa_id BIGINT', tabla);
        -- Para las tablas de trazabilidad se prioriza el dueño real del padre.
        IF tabla = 'registro_vestidor' THEN
            UPDATE registro_vestidor rv SET empresa_id = p.empresa_id
            FROM producto p WHERE rv.producto_id = p.id AND rv.empresa_id IS NULL;
        ELSIF tabla = 'producto_embedding' THEN
            UPDATE producto_embedding pe SET empresa_id = p.empresa_id
            FROM producto p WHERE pe.producto_id = p.id AND pe.empresa_id IS NULL;
        ELSIF tabla = 'cliente_favorito' THEN
            UPDATE cliente_favorito cf SET empresa_id = c.empresa_id
            FROM cliente c WHERE cf.cliente_id = c.id AND cf.empresa_id IS NULL;
        ELSIF tabla = 'cliente_preferencia_ia' THEN
            UPDATE cliente_preferencia_ia cp SET empresa_id = c.empresa_id
            FROM cliente c WHERE cp.cliente_id = c.id AND cp.empresa_id IS NULL;
        ELSIF tabla = 'proveedor_usuario' THEN
            UPDATE proveedor_usuario pu SET empresa_id = p.empresa_id
            FROM proveedor p WHERE pu.proveedor_id = p.id AND pu.empresa_id IS NULL;
        END IF;
        IF tabla = 'usuario' THEN
            -- Una cuenta global ADMIN_SAAS conserva empresa_id NULL.
            UPDATE usuario u SET empresa_id = empresa_stylear_id
            WHERE u.empresa_id IS NULL
              AND NOT EXISTS (
                  SELECT 1 FROM usuario_rol ur JOIN rol r ON r.id = ur.rol_id
                  WHERE ur.usuario_id = u.id AND r.nombre = 'ADMIN_SAAS'
              );
            SELECT count(*) INTO total_sin_empresa FROM usuario u
            WHERE u.empresa_id IS NULL
              AND NOT EXISTS (
                  SELECT 1 FROM usuario_rol ur JOIN rol r ON r.id = ur.rol_id
                  WHERE ur.usuario_id = u.id AND r.nombre = 'ADMIN_SAAS'
              );
        ELSIF tabla = 'sesion' THEN
            UPDATE sesion s SET empresa_id = u.empresa_id
            FROM usuario u
            WHERE s.usuario_id = u.id AND s.empresa_id IS NULL
              AND u.empresa_id IS NOT NULL;
            SELECT count(*) INTO total_sin_empresa FROM sesion s
            JOIN usuario u ON u.id = s.usuario_id
            WHERE s.empresa_id IS NULL AND u.empresa_id IS NOT NULL;
        ELSIF tabla = 'bitacora' THEN
            -- Eventos anonimos y del AS son de plataforma, no de StyleAR.
            UPDATE bitacora b SET empresa_id = u.empresa_id
            FROM usuario u
            WHERE b.usuario_id = u.id AND b.empresa_id IS NULL
              AND u.empresa_id IS NOT NULL;
            SELECT count(*) INTO total_sin_empresa FROM bitacora b
            JOIN usuario u ON u.id = b.usuario_id
            WHERE b.empresa_id IS NULL AND u.empresa_id IS NOT NULL;
        ELSE
            EXECUTE format(
                'UPDATE public.%I SET empresa_id = $1 WHERE empresa_id IS NULL', tabla
            ) USING empresa_stylear_id;
            EXECUTE format(
                'SELECT count(*) FROM public.%I WHERE empresa_id IS NULL', tabla
            ) INTO total_sin_empresa;
        END IF;
        IF total_sin_empresa > 0 THEN
            RAISE EXCEPTION '% conserva % filas sin empresa', tabla, total_sin_empresa;
        END IF;

        IF NOT EXISTS (
            SELECT 1 FROM pg_constraint
            WHERE conrelid = to_regclass(format('public.%I', tabla))
              AND conname = 'fk_' || tabla || '_empresa'
        ) THEN
            EXECUTE format(
                'ALTER TABLE public.%I ADD CONSTRAINT %I FOREIGN KEY (empresa_id) REFERENCES empresa(id)',
                tabla, 'fk_' || tabla || '_empresa'
            );
        END IF;
        EXECUTE format(
            'CREATE INDEX IF NOT EXISTS %I ON public.%I (empresa_id)',
            'idx_' || tabla || '_empresa', tabla
        );
        IF tabla NOT IN ('usuario', 'sesion', 'bitacora') THEN
            EXECUTE format('ALTER TABLE public.%I ALTER COLUMN empresa_id SET NOT NULL', tabla);
        END IF;
    END LOOP;

    -- Las tablas dependientes toman la empresa de su padre, sin adivinarla a
    -- partir de un codigo proporcionado por el cliente.
    FOR relacion IN
        SELECT * FROM (VALUES
            ('direccion_cliente', 'cliente', 'cliente_id'),
            ('imagen_producto', 'producto', 'producto_id'),
            ('producto_proveedor', 'producto', 'producto_id'),
            ('producto_coleccion', 'producto', 'producto_id'),
            ('promocion_producto', 'promocion', 'promocion_id'),
            ('promocion_sucursal', 'promocion', 'promocion_id'),
            ('carrito_item', 'carrito', 'carrito_id'),
            ('reserva_detalle', 'reserva', 'reserva_id'),
            ('venta_detalle', 'venta', 'venta_id'),
            ('transferencia_stock_detalle', 'transferencia_stock', 'transferencia_id'),
            ('devolucion_detalle', 'devolucion', 'devolucion_id')
        ) AS x(tabla, padre, columna_padre)
    LOOP
        IF to_regclass(format('public.%I', relacion.tabla)) IS NULL THEN
            RAISE EXCEPTION 'Falta tabla dependiente para multitenant: %', relacion.tabla;
        END IF;
        EXECUTE format('ALTER TABLE public.%I ADD COLUMN IF NOT EXISTS empresa_id BIGINT', relacion.tabla);
        EXECUTE format(
            'UPDATE public.%I hijo SET empresa_id = padre.empresa_id FROM public.%I padre WHERE hijo.%I = padre.id AND hijo.empresa_id IS NULL',
            relacion.tabla, relacion.padre, relacion.columna_padre
        );
        EXECUTE format('SELECT count(*) FROM public.%I WHERE empresa_id IS NULL', relacion.tabla)
            INTO total_sin_empresa;
        IF total_sin_empresa > 0 THEN
            RAISE EXCEPTION '% conserva % filas sin empresa de padre', relacion.tabla, total_sin_empresa;
        END IF;
        IF NOT EXISTS (
            SELECT 1 FROM pg_constraint
            WHERE conrelid = to_regclass(format('public.%I', relacion.tabla))
              AND conname = 'fk_' || relacion.tabla || '_empresa'
        ) THEN
            EXECUTE format(
                'ALTER TABLE public.%I ADD CONSTRAINT %I FOREIGN KEY (empresa_id) REFERENCES empresa(id)',
                relacion.tabla, 'fk_' || relacion.tabla || '_empresa'
            );
        END IF;
        EXECUTE format('CREATE INDEX IF NOT EXISTS %I ON public.%I (empresa_id)',
            'idx_' || relacion.tabla || '_empresa', relacion.tabla);
        EXECUTE format('ALTER TABLE public.%I ALTER COLUMN empresa_id SET NOT NULL', relacion.tabla);
    END LOOP;
END $$;

