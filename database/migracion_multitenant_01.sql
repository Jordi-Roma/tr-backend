CREATE OR REPLACE FUNCTION validar_alcance_rol_usuario() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    rol_nombre TEXT;
    empresa_usuario BIGINT;
BEGIN
    SELECT nombre INTO rol_nombre FROM rol WHERE id=NEW.rol_id;
    SELECT empresa_id INTO empresa_usuario FROM usuario WHERE id=NEW.usuario_id;
    IF (rol_nombre = 'ADMIN_SAAS' AND empresa_usuario IS NOT NULL)
       OR (rol_nombre <> 'ADMIN_SAAS' AND empresa_usuario IS NULL) THEN
        RAISE EXCEPTION 'Rol incompatible con alcance de empresa del usuario';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER trg_usuario_rol_alcance
BEFORE INSERT OR UPDATE ON usuario_rol
FOR EACH ROW EXECUTE FUNCTION validar_alcance_rol_usuario();

CREATE OR REPLACE FUNCTION impedir_cambio_empresa() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.empresa_id IS DISTINCT FROM OLD.empresa_id THEN
        RAISE EXCEPTION 'No se puede trasladar un registro entre empresas';
    END IF;
    RETURN NEW;
END $$;
DO $$
DECLARE
    r RECORD;
BEGIN
    FOR r IN
        SELECT c.relname AS tabla
        FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
        JOIN pg_attribute a ON a.attrelid=c.oid AND a.attname='empresa_id' AND NOT a.attisdropped
        WHERE n.nspname='public' AND c.relkind='r'
          AND c.relname NOT IN ('empresa','suscripcion')
    LOOP
        EXECUTE format('CREATE TRIGGER %I BEFORE UPDATE ON public.%I FOR EACH ROW EXECUTE FUNCTION impedir_cambio_empresa()',
            'trg_' || r.tabla || '_empresa_inmutable', r.tabla);
    END LOOP;
END $$;

