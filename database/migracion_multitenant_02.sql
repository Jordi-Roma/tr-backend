-- Correcciones y auditoría SaaS. Se aplica con init_db.py, una sola vez.
CREATE TABLE IF NOT EXISTS evento_plataforma (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id BIGINT NOT NULL REFERENCES usuario(id),
    empresa_id BIGINT REFERENCES empresa(id),
    accion VARCHAR(80) NOT NULL,
    recurso_id VARCHAR(100),
    fecha TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_evento_plataforma_empresa ON evento_plataforma(empresa_id, fecha);

CREATE TABLE IF NOT EXISTS respaldo (
    id UUID PRIMARY KEY,
    empresa_id BIGINT REFERENCES empresa(id),
    tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('GLOBAL', 'EMPRESA')),
    creado_por BIGINT NOT NULL REFERENCES usuario(id),
    fecha TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    vence_en TIMESTAMPTZ NOT NULL,
    sha256 VARCHAR(64) NOT NULL,
    bytes BIGINT NOT NULL CHECK (bytes > 0),
    estado VARCHAR(20) NOT NULL DEFAULT 'DISPONIBLE'
        CHECK (estado IN ('DISPONIBLE', 'ELIMINADO'))
);

-- Las auditorías SaaS afectan a una empresa sin convertir al actor AS en
-- integrante comercial de ella. Son de plataforma, no bitácoras comerciales.
DROP TRIGGER IF EXISTS trg_evento_plataforma_empresa_inmutable ON evento_plataforma;
DROP TRIGGER IF EXISTS trg_respaldo_empresa_inmutable ON respaldo;

-- La restauración selectiva difiere las comprobaciones FK hasta completar la
-- misma transacción. Las operaciones normales siguen comprobándose al instante.
DO $$
DECLARE r RECORD;
BEGIN
    FOR r IN SELECT c.conname, t.relname FROM pg_constraint c
        JOIN pg_class t ON t.oid=c.conrelid
        JOIN pg_namespace n ON n.oid=t.relnamespace
        WHERE c.contype='f' AND n.nspname='public'
    LOOP
        EXECUTE format('ALTER TABLE public.%I ALTER CONSTRAINT %I DEFERRABLE INITIALLY IMMEDIATE',r.relname,r.conname);
    END LOOP;
END $$;
