-- Compatibilidad con INSERT legados y barrera de integridad entre referencias:
-- la empresa de cada hijo se deriva del padre si no vino explicitamente, y
-- toda referencia secundaria debe pertenecer a la misma empresa.
CREATE OR REPLACE FUNCTION validar_empresa_de_padre() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    clave_padre BIGINT;
    empresa_padre BIGINT;
    filas BIGINT;
BEGIN
    clave_padre := (to_jsonb(NEW)->>TG_ARGV[1])::BIGINT;
    IF clave_padre IS NULL THEN
        RETURN NEW;
    END IF;
    EXECUTE format('SELECT empresa_id FROM public.%I WHERE id = $1', TG_ARGV[0])
        INTO empresa_padre USING clave_padre;
    GET DIAGNOSTICS filas = ROW_COUNT;
    IF filas = 0 THEN
        RAISE EXCEPTION 'No existe el padre %.%=%', TG_ARGV[0], TG_ARGV[1], clave_padre;
    END IF;
    IF NEW.empresa_id IS NULL THEN
        NEW.empresa_id := empresa_padre;
    ELSIF NEW.empresa_id IS DISTINCT FROM empresa_padre THEN
        RAISE EXCEPTION 'Referencia cruzada entre empresas en %.%', TG_TABLE_NAME, TG_ARGV[1];
    END IF;
    RETURN NEW;
END $$;

