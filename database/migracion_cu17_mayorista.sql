-- Paquetes explícitos: nunca convertir unidades normales en mayorista por cantidad.
CREATE TABLE precio_mayorista (
 empresa_id BIGINT NOT NULL REFERENCES empresa(id), producto_id BIGINT NOT NULL REFERENCES producto(id),
 tipo VARCHAR(10) NOT NULL CHECK(tipo IN ('CUARTA','MEDIA','DOCENA')),
 descuento NUMERIC(5,2) CHECK(descuento>0 AND descuento<100), habilitado BOOLEAN NOT NULL DEFAULT FALSE,
 version INTEGER NOT NULL DEFAULT 1, actualizado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(empresa_id,producto_id,tipo), CHECK(NOT habilitado OR descuento IS NOT NULL)
);
CREATE TABLE carrito_paquete (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 empresa_id BIGINT NOT NULL REFERENCES empresa(id), carrito_id BIGINT NOT NULL REFERENCES carrito(id),
 producto_id BIGINT NOT NULL REFERENCES producto(id), tipo VARCHAR(10) NOT NULL CHECK(tipo IN ('CUARTA','MEDIA','DOCENA')),
 clave UUID NOT NULL, huella CHAR(64) NOT NULL, activo BOOLEAN NOT NULL DEFAULT TRUE,
 UNIQUE(carrito_id,clave)
);
ALTER TABLE carrito_item ADD COLUMN paquete_id BIGINT REFERENCES carrito_paquete(id);
DROP INDEX uq_carrito_item_variante_sucursal_activo;
CREATE UNIQUE INDEX uq_carrito_item_variante_sucursal_activo ON carrito_item(carrito_id,producto_variante_id,COALESCE(sucursal_id,0)) WHERE activo AND paquete_id IS NULL;
CREATE UNIQUE INDEX uq_carrito_paquete_variante ON carrito_item(paquete_id,producto_variante_id) WHERE activo AND paquete_id IS NOT NULL;
