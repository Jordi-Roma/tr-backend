CREATE TABLE delivery_cotizacion (
 id UUID PRIMARY KEY, empresa_id BIGINT NOT NULL REFERENCES empresa(id), usuario_id BIGINT NOT NULL REFERENCES usuario(id),
 cliente_id BIGINT NOT NULL REFERENCES cliente(id), sucursal_id BIGINT NOT NULL REFERENCES sucursal(id),
 solicitud JSONB NOT NULL, huella CHAR(64) NOT NULL, origen_latitud NUMERIC(10,7) NOT NULL, origen_longitud NUMERIC(10,7) NOT NULL,
 distancia_km NUMERIC(10,2) NOT NULL CHECK(distancia_km>=0), tiempo_estimado_min INTEGER NOT NULL CHECK(tiempo_estimado_min>0),
 costo_delivery NUMERIC(12,2) NOT NULL CHECK(costo_delivery>0), ruta JSONB NOT NULL,
 creada_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, vence_en TIMESTAMPTZ NOT NULL,
 orden_pago_id BIGINT UNIQUE REFERENCES orden_pago(id)
);
ALTER TABLE orden_pago ADD COLUMN delivery_cotizacion_id UUID REFERENCES delivery_cotizacion(id);
ALTER TABLE delivery ADD COLUMN cotizacion_id UUID UNIQUE REFERENCES delivery_cotizacion(id);
ALTER TABLE delivery ADD COLUMN version INTEGER NOT NULL DEFAULT 1;
ALTER TABLE delivery ADD COLUMN incidencia_abierta BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE delivery ADD COLUMN recepcion_confirmada_por BIGINT REFERENCES usuario(id);
ALTER TABLE delivery DROP CONSTRAINT ck_delivery_estado;
ALTER TABLE delivery ADD CONSTRAINT ck_delivery_estado CHECK(estado IN ('PENDIENTE_PAGO','PENDIENTE','EN_PREPARACION','EN_CAMINO','ENTREGADO','CANCELADO'));
-- Conservar registros anteriores, pero impedir despachar los que aún no fueron pagados.
UPDATE delivery d SET estado='PENDIENTE_PAGO' FROM venta v WHERE d.venta_id=v.id AND d.empresa_id=v.empresa_id
 AND d.estado IN ('PENDIENTE','EN_PREPARACION') AND (v.estado<>'COMPLETADA' OR NOT EXISTS(
 SELECT 1 FROM orden_pago o WHERE o.venta_id=v.id AND o.empresa_id=v.empresa_id AND o.estado='PAGADO' AND o.monto_total=v.total));
CREATE TABLE delivery_seguimiento (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, empresa_id BIGINT NOT NULL REFERENCES empresa(id),
 delivery_id BIGINT NOT NULL REFERENCES delivery(id), usuario_id BIGINT REFERENCES usuario(id),
 tipo VARCHAR(20) NOT NULL CHECK(tipo IN ('REGISTRO','ESTADO','INCIDENCIA','RESOLUCION')),
 estado_anterior VARCHAR(30), estado_nuevo VARCHAR(30) NOT NULL, observacion VARCHAR(500),
 version INTEGER NOT NULL, fecha TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(delivery_id,version)
);
