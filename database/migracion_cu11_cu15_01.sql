CREATE TABLE numeracion_nota_venta (
    empresa_id BIGINT PRIMARY KEY REFERENCES empresa(id),
    ultimo BIGINT NOT NULL CHECK (ultimo > 0)
);
CREATE TABLE nota_venta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT NOT NULL REFERENCES empresa(id),
    venta_id BIGINT NOT NULL UNIQUE REFERENCES venta(id),
    numero BIGINT NOT NULL,
    datos JSONB NOT NULL,
    fecha_emision TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (empresa_id, numero),
    CHECK (jsonb_typeof(datos) = 'object')
);
CREATE FUNCTION validar_nota_venta_empresa() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM venta WHERE id=NEW.venta_id AND empresa_id=NEW.empresa_id) THEN
        RAISE EXCEPTION 'La nota de venta no corresponde a la empresa.';
    END IF;
    IF TG_OP='UPDATE' THEN
        RAISE EXCEPTION 'Una nota de venta emitida es inmutable.';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER trg_nota_venta_empresa BEFORE INSERT OR UPDATE ON nota_venta
    FOR EACH ROW EXECUTE FUNCTION validar_nota_venta_empresa();

-- Mismo precio efectivo para filtros/orden, carrito y cierre de venta.
CREATE FUNCTION precio_catalogo(variante bigint, empresa bigint, sucursal_elegida bigint)
RETURNS numeric LANGUAGE sql STABLE AS $$
    SELECT round(greatest(0, CASE
        WHEN pr.tipo_descuento='PORCENTAJE' THEN pp.precio*(1-pr.valor/100)
        WHEN pr.tipo_descuento='MONTO_FIJO' THEN pp.precio-pr.valor
        ELSE pp.precio END),2)
    FROM producto_variante v
    JOIN LATERAL (SELECT precio FROM precio_producto p
        WHERE p.producto_variante_id=v.id AND p.empresa_id=v.empresa_id AND p.activo
        AND CURRENT_DATE BETWEEN p.fecha_inicio AND coalesce(p.fecha_fin,CURRENT_DATE)
        ORDER BY p.fecha_inicio DESC,p.id DESC LIMIT 1) pp ON TRUE
    LEFT JOIN LATERAL (
        SELECT pro.tipo_descuento,pro.valor FROM promocion pro
        JOIN promocion_producto vinc ON vinc.promocion_id=pro.id AND vinc.empresa_id=pro.empresa_id AND vinc.activo
        WHERE vinc.producto_id=v.producto_id AND pro.empresa_id=v.empresa_id AND pro.activo
        AND CURRENT_DATE BETWEEN pro.fecha_inicio AND pro.fecha_fin
        AND (NOT EXISTS(SELECT 1 FROM promocion_sucursal ps WHERE ps.promocion_id=pro.id AND ps.empresa_id=pro.empresa_id AND ps.activo)
             OR EXISTS(SELECT 1 FROM promocion_sucursal ps WHERE ps.promocion_id=pro.id AND ps.empresa_id=pro.empresa_id AND ps.activo AND ps.sucursal_id=sucursal_elegida))
        ORDER BY pro.valor DESC,pro.id DESC LIMIT 1
    ) pr ON TRUE
    WHERE v.id=variante AND v.empresa_id=empresa AND v.activo
$$;
