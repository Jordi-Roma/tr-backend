-- Claves de reintento por usuario, empresa y operación; nunca por dispositivo.
CREATE TABLE operacion_comercial (
    empresa_id BIGINT NOT NULL REFERENCES empresa(id),
    usuario_id BIGINT NOT NULL REFERENCES usuario(id),
    operacion VARCHAR(40) NOT NULL,
    clave UUID NOT NULL,
    huella CHAR(64) NOT NULL,
    recurso_id BIGINT NOT NULL,
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (empresa_id, usuario_id, operacion, clave)
);
CREATE TRIGGER trg_operacion_comercial_usuario BEFORE INSERT OR UPDATE ON operacion_comercial
    FOR EACH ROW EXECUTE FUNCTION validar_empresa_de_padre('usuario','usuario_id');
CREATE TRIGGER trg_operacion_comercial_empresa BEFORE UPDATE ON operacion_comercial
    FOR EACH ROW EXECUTE FUNCTION impedir_cambio_empresa();

