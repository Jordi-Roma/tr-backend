    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporte_id BIGINT NOT NULL REFERENCES reporte_programado(id) ON DELETE CASCADE,
    ocurrencia TIMESTAMPTZ NOT NULL,
    estado VARCHAR(20) NOT NULL CHECK (estado IN ('INICIADO','ENVIADO','FALLIDO','OMITIDO')),
    iniciado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
