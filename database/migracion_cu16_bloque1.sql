-- CU16 y base CU20: sólo habilita el entorno de pruebas de cada comercio.
CREATE TABLE configuracion_pago_empresa (
    empresa_id BIGINT PRIMARY KEY REFERENCES empresa(id) ON DELETE RESTRICT,
    modo VARCHAR(15) NOT NULL DEFAULT 'PRUEBA' CHECK(modo='PRUEBA'),
    stripe_habilitado BOOLEAN NOT NULL DEFAULT FALSE,
    qr_habilitado BOOLEAN NOT NULL DEFAULT FALSE,
    titular VARCHAR(180) NOT NULL DEFAULT '',
    banco VARCHAR(30) NOT NULL DEFAULT 'BCP' CHECK(banco='BCP'),
    version INTEGER NOT NULL DEFAULT 1,
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
ALTER TABLE orden_pago ADD COLUMN modo_pago VARCHAR(15) NOT NULL DEFAULT 'LEGADO';
ALTER TABLE orden_pago ADD COLUMN clave_operacion UUID;
ALTER TABLE orden_pago ADD COLUMN solicitud_huella VARCHAR(64);
ALTER TABLE orden_pago ADD COLUMN titular_pago VARCHAR(180);
ALTER TABLE orden_pago ADD COLUMN carrito_origen_id BIGINT REFERENCES carrito(id);
ALTER TABLE orden_pago ADD COLUMN configuracion_version INTEGER;
ALTER TABLE orden_pago ADD COLUMN pago_recibido BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE orden_pago ADD COLUMN motivo_incidencia TEXT;
ALTER TABLE orden_pago ADD COLUMN proveedor_pago_id VARCHAR(255);
ALTER TABLE orden_pago DROP CONSTRAINT IF EXISTS ck_orden_pago_estado;
ALTER TABLE orden_pago ADD CONSTRAINT ck_orden_pago_estado CHECK(estado IN
    ('PENDIENTE','PAGADO','RECHAZADO','EXPIRADO','CANCELADO','REEMBOLSO_PENDIENTE','REEMBOLSADO'));
CREATE UNIQUE INDEX uq_cu16_clave ON orden_pago(empresa_id,cliente_id,clave_operacion) WHERE clave_operacion IS NOT NULL;
CREATE UNIQUE INDEX uq_cu16_carrito_pendiente ON orden_pago(empresa_id,carrito_origen_id)
    WHERE modo_pago='PRUEBA' AND estado='PENDIENTE';
CREATE UNIQUE INDEX uq_cu16_pago_externo ON orden_pago(empresa_id,proveedor,proveedor_pago_id)
    WHERE proveedor_pago_id IS NOT NULL;
CREATE TABLE evento_pago (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT NOT NULL REFERENCES empresa(id),
    orden_id BIGINT NOT NULL REFERENCES orden_pago(id),
    proveedor VARCHAR(30) NOT NULL,
    evento_id VARCHAR(255) NOT NULL,
    huella VARCHAR(64) NOT NULL,
    tipo VARCHAR(30) NOT NULL,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(empresa_id,proveedor,evento_id)
);
CREATE TABLE reembolso_pago (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT NOT NULL REFERENCES empresa(id),
    orden_id BIGINT NOT NULL UNIQUE REFERENCES orden_pago(id),
    monto NUMERIC(12,2) NOT NULL CHECK(monto>0),
    moneda VARCHAR(10) NOT NULL,
    metodo VARCHAR(40) NOT NULL,
    motivo TEXT NOT NULL,
    estado VARCHAR(30) NOT NULL DEFAULT 'PENDIENTE' CHECK(estado IN ('PENDIENTE','CONFIRMADO','FALLIDO')),
    referencia VARCHAR(255),
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE notificacion_usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT NOT NULL REFERENCES empresa(id),
    usuario_id BIGINT NOT NULL REFERENCES usuario(id),
    clave VARCHAR(200) NOT NULL,
    titulo VARCHAR(180) NOT NULL,
    mensaje TEXT NOT NULL,
    orden_id BIGINT REFERENCES orden_pago(id),
    leida BOOLEAN NOT NULL DEFAULT FALSE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE(empresa_id,usuario_id,clave)
);
CREATE TABLE dispositivo_push (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa_id BIGINT NOT NULL REFERENCES empresa(id),
    usuario_id BIGINT NOT NULL REFERENCES usuario(id),
    instalacion_id UUID NOT NULL UNIQUE,
    sesion_id BIGINT REFERENCES sesion(id),
    version_acceso INTEGER NOT NULL DEFAULT 0,
    token TEXT NOT NULL UNIQUE,
    plataforma VARCHAR(20) NOT NULL CHECK(plataforma IN ('android','ios','web')),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE salida_push (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notificacion_id BIGINT NOT NULL REFERENCES notificacion_usuario(id),
    dispositivo_id BIGINT NOT NULL REFERENCES dispositivo_push(id),
    estado VARCHAR(25) NOT NULL DEFAULT 'PENDIENTE' CHECK(estado IN ('PENDIENTE','ENVIADO','FALLIDO','OMITIDO')),
    intentos INTEGER NOT NULL DEFAULT 0,
    ultimo_error VARCHAR(255),
    proveedor_referencia VARCHAR(255),
    UNIQUE(notificacion_id,dispositivo_id)
);
